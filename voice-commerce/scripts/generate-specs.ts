export function openApi() {
  const paths: Record<string, Record<string, unknown>> = {};
  for (const op of OPS) {
    const parameters: unknown[] = [
      ...(op.params ?? []).map((p) => ({ name: p, in: "path", required: true, schema: { type: "string" } })),
      { name: "GIMME-API-Version", in: "header", required: false, schema: { type: "string", enum: ["1.0"] } },
      { name: "X-Request-Id", in: "header", required: false, schema: { type: "string" } },
      { name: "X-Correlation-Id", in: "header", required: false, schema: { type: "string" } },
      ...(op.idempotencyHeader ? [{ name: "Idempotency-Key", in: "header", required: false, schema: { type: "string", minLength: 8, maxLength: 200 } }] : []),
    ];
    if (op.query) {
      const q = schema(op.query, "input") as { properties: Record<string, unknown>; required?: string[] };
      for (const [k, v] of Object.entries(q.properties)) parameters.push({ name: k, in: "query", required: q.required?.includes(k) ?? false, schema: v });
    }
    const status = String(op.status ?? 200);
    paths[op.path] ??= {};
    paths[op.path]![op.method] = {
      summary: op.summary,
      ...(op.description ? { description: op.description } : {}),
      operationId: `${op.method}${op.path.replace(/[{}]/g, "").replace(/[/-](\w)/g, (_m, c: string) => c.toUpperCase())}`,
      security: [{ oauth2: op.scopes }],
      parameters,
      ...(op.body ? { requestBody: { required: true, content: { "application/json": { schema: schema(op.body, "input") } } } } : {}),
      responses: {
        [status]: { description: "OK", content: { "application/json": { schema: op.response ? schema(op.response, "output") : {} } } },
        default: { description: "Error", content: { "application/json": { schema: { $ref: "#/components/schemas/Error" } } } },
      },
    };
  }
  return {
    openapi: "3.1.0",
    info: {
      title: "GIMME Voice API",
      version: "1.0.0",
      description:
        "Platform-neutral voice commerce API. Apple, Google and agent adapters call this; it maps onto the same service as the GIMME MCP tools. Amounts are decimal NZD. Every error body has error_code, message, recoverable and suggested_action.",
    },
    servers: [{ url: "https://voice.gimme.example", description: "Production (placeholder)" }, { url: "http://localhost:8787", description: "Sandbox" }],
    components: {
      securitySchemes: {
        oauth2: {
          type: "oauth2",
          description: "Tokens are issued by GIMME's authorization server (account linking). This API is a resource server only.",
          flows: {
            authorizationCode: {
              authorizationUrl: "https://auth.gimme.example/authorize",
              tokenUrl: "https://auth.gimme.example/token",
              scopes: Object.fromEntries(ALL_SCOPES.map((s) => [s, SCOPE_DESCRIPTIONS[s]])),
            },
          },
        },
      },
      schemas: { Error: schema(C.ErrorBody, "output") },
    },
    paths,
  };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(join(DOCS, "openapi.json"), `${JSON.stringify(openApi(), null, 2)}\n`);
  writeFileSync(join(DOCS, "mcp-tools.json"), `${JSON.stringify(mcpToolsJson(), null, 2)}\n`);
  writeFileSync(join(DOCS, "mcp-tools.md"), mcpToolsMarkdown());
  process.stdout.write("Wrote docs/openapi.json, docs/mcp-tools.json, docs/mcp-tools.md\n");
}
