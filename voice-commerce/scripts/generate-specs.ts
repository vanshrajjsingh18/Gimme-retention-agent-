/**
 * Generates docs/openapi.json, docs/mcp-tools.json and docs/mcp-tools.md
 * from the contract schemas and tool definitions. Run: npm run docs:generate
 * A test fails if the committed files are stale.
 */

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { z } from "zod";
import * as C from "../src/contracts/schemas.js";
import { ERROR_CODES, ERROR_SPECS } from "../src/domain/errors.js";
import { TOOLS } from "../src/mcp/tools.js";
import { ALL_SCOPES, SCOPE_DESCRIPTIONS } from "../src/security/scopes.js";

const DOCS = join(dirname(fileURLToPath(import.meta.url)), "..", "docs");

const schema = (s: z.ZodType, io: "input" | "output") => {
  const j = z.toJSONSchema(s, { io, unrepresentable: "any" }) as Record<string, unknown>;
  delete j.$schema;
  return j;
};

// ------------------------------------------------------------ MCP tools

export function mcpToolsJson() {
  return {
    server: "gimme-voice-commerce",
    contract_version: "1.0",
    transports: ["streamable-http (/mcp, OAuth 2.0 bearer)", "stdio (development)"],
    tools: TOOLS.map((t) => ({
      name: t.name,
      title: t.title,
      description: t.description,
      contract_version: t.contract_version,
      classification: t.classification,
      requires_authentication: t.requires_authentication,
      required_scopes: t.required_scopes,
      requires_confirmation: t.requires_confirmation,
      has_side_effect: t.has_side_effect,
      side_effects: t.side_effects,
      idempotent: t.idempotent,
      idempotency: t.idempotency,
      error_codes: t.error_codes,
      inputSchema: schema(t.inputSchema, "input"),
      outputSchema: schema(t.outputSchema, "output"),
    })),
    error_schema: schema(C.ErrorBody, "output"),
  };
}

export function mcpToolsMarkdown(): string {
  const out: string[] = [
    "# GIMME MCP tool specification",
    "",
    "_Generated by `npm run docs:generate` from `src/mcp/tools.ts` and `src/contracts/schemas.ts`. Do not edit by hand._",
    "",
    "Machine-readable version, with full JSON Schemas: [`mcp-tools.json`](mcp-tools.json).",
    "",
    "| Tool | Class | Scopes | Side effect | Idempotent | Needs customer confirmation |",
    "| --- | --- | --- | --- | --- | --- |",
    ...TOOLS.map(
      (t) =>
        `| [\`${t.name}\`](#${t.name}) | ${t.classification} | ${t.required_scopes.map((s) => `\`${s}\``).join(" ")} | ${t.has_side_effect ? "yes" : "no"} | ${t.idempotent ? "yes" : "no"} | ${t.requires_confirmation ? "**yes**" : "no"} |`,
    ),
    "",
  ];
  for (const t of TOOLS) {
    const input = schema(t.inputSchema, "input") as { properties?: Record<string, { description?: string; type?: string }>; required?: string[] };
    out.push(`## ${t.name}`, "", t.description, "");
    out.push(`- **Classification:** ${t.classification}`);
    out.push(`- **Scopes:** ${t.required_scopes.map((s) => `\`${s}\``).join(", ")}`);
    out.push(`- **Side effects:** ${t.side_effects}`);
    out.push(`- **Idempotency:** ${t.idempotency}`);
    out.push(`- **Errors:** ${t.error_codes.map((e) => `\`${e}\``).join(", ")}`, "");
    out.push("| Argument | Required | Description |", "| --- | --- | --- |");
    for (const [k, v] of Object.entries(input.properties ?? {})) {
      out.push(`| \`${k}\` | ${input.required?.includes(k) ? "yes" : "no"} | ${(v.description ?? v.type ?? "").replace(/\|/g, "\\|")} |`);
    }
    out.push("");
  }
  out.push("## Error codes", "", "| Code | HTTP | Recoverable | Suggested action | Default message |", "| --- | --- | --- | --- | --- |");
  for (const c of ERROR_CODES) {
    const s = ERROR_SPECS[c];
    out.push(`| \`${c}\` | ${s.http} | ${s.recoverable ? "yes" : "no"} | \`${s.action}\` | ${s.message} |`);
  }
  out.push("");
  return out.join("\n");
}

